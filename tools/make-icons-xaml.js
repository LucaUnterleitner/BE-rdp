// Converts the Electron icon set (src/renderer/js/icons.js, Lucide paths, ISC license) into WPF geometries.
// Usage: node windows-app/tools/make-icons-xaml.js <icons.js> <out Icons.xaml>
'use strict';
const fs = require('node:fs');

const [, , src, out] = process.argv;
const text = fs.readFileSync(src, 'utf8');
const body = text.slice(text.indexOf('const P = {'), text.indexOf('};', text.indexOf('const P = {')));
const entries = [...body.matchAll(/^\s+(\w+): '([^']*)',?$/gm)].map((m) => [m[1], m[2]]);

const num = (v) => Number(v);
function rectPath(a) {
  const x = num(a.x), y = num(a.y), w = num(a.width), h = num(a.height), r = num(a.rx || 0);
  if (!r) return `M${x},${y} H${x + w} V${y + h} H${x} Z`;
  return `M${x + r},${y} H${x + w - r} A${r},${r} 0 0 1 ${x + w},${y + r} V${y + h - r} A${r},${r} 0 0 1 ${x + w - r},${y + h} H${x + r} A${r},${r} 0 0 1 ${x},${y + h - r} V${y + r} A${r},${r} 0 0 1 ${x + r},${y} Z`;
}
function circlePath(a) {
  const cx = num(a.cx), cy = num(a.cy), r = num(a.r);
  return `M${cx - r},${cy} A${r},${r} 0 1 0 ${cx + r},${cy} A${r},${r} 0 1 0 ${cx - r},${cy} Z`;
}
function attrs(s) {
  return Object.fromEntries([...s.matchAll(/(\w+)="([^"]*)"/g)].map((m) => [m[1], m[2]]));
}
const lines = entries.map(([name, svg]) => {
  const parts = [...svg.matchAll(/<(path|rect|circle)\s([^>]*)\/>/g)].map(([, tag, a]) => {
    const at = attrs(a);
    if (tag === 'path') return at.d;
    if (tag === 'rect') return rectPath(at);
    return circlePath(at);
  });
  return `  <Geometry x:Key="Icon.${name}" po:Freeze="True">F0 ${parts.join(' ')}</Geometry>`;
});
fs.writeFileSync(out, `<!-- Generated by tools/make-icons-xaml.js from the Electron icon set (Lucide, ISC license). Do not edit by hand. -->
<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"
                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml"
                    xmlns:po="http://schemas.microsoft.com/winfx/2006/xaml/presentation/options"
                    xmlns:mc="http://schemas.openxmlformats.org/markup-compatibility/2006"
                    mc:Ignorable="po">
${lines.join('\n')}
</ResourceDictionary>
`);
console.log(`${entries.length} icons -> ${out}`);
